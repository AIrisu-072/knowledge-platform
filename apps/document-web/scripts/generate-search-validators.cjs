const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const Ajv = require('ajv');
const standaloneCode = require('ajv/dist/standalone').default;
const { listSchema, detailSchema } = require('../src/application/search-schemas.cjs');
const ajv = new Ajv({ coerceTypes: true, useDefaults: true, removeAdditional: 'all', code: { source: true, esm: true } });
ajv.addSchema(listSchema, 'list');
ajv.addSchema(detailSchema, 'detail');
const output = '// Generated by scripts/generate-search-validators.cjs; do not edit.\n' + standaloneCode(ajv, { validateList: 'list', validateDetail: 'detail' }) + '\n';
const destination = resolve(__dirname, '../src/application/search-validators.generated.js');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Search validators are stale; run schemas:generate and review the generated diff');
} else writeFileSync(destination, output);
